#!/usr/bin/env python3
"""Exact, deliberately *not PSD-claimed*, source-rational C2 affine Gram.

Known rank-406 support face plus exact native stationarity ensures a preimage.
Deterministic lexicographic 406-by-406 minor is recorded in
C2_RANK406_MODULAR_PIVOTS.json, generated by verify_rank_mod65521.py.
Usage: python generate_affine_preimage.py --source 1 13/600 47/15 ...
Parameter order in this file is a b c t r (NOT c a b t r).
The command can take substantial rational-elimination time.
"""
import argparse,json
import sympy as sp
from c2_fixed_map import coefficient_map,is_strict_native
from verify_exact_certificates import target_exact
p=argparse.ArgumentParser()
p.add_argument('--source',nargs=5,required=True)
p.add_argument('--output',default='C2_AFFINE_ONLY.json')
a=p.parse_args()
assert is_strict_native(a.source)
M=coefficient_map()
with open('C2_RANK406_MODULAR_PIVOTS.json') as f:piv=json.load(f)
assert piv['rank']==406
pts=piv['pivot_columns_residues_and_original_rows']
cols=[x[0] for x in pts];rows=[x[2] for x in pts]
A=sp.zeros(406)
for j, col in enumerate(cols):
 for row,coef in M['sparse_columns'][col].items():
  if row in rows:A[rows.index(row),j]=coef
rhs=target_exact(a.source,M)
sol=A.inv()*sp.Matrix([rhs[row] for row in rows])
coef=[sp.Rational(0)]*len(M['columns'])
for j,col in enumerate(cols):coef[col]=sol[j]
check=[sp.Rational(0)]*len(M['row_keys'])
for col,sc in enumerate(coef):
 if sc:
  for row,w in M['sparse_columns'][col].items():check[row]+=sc*w
assert check==rhs,'RHS violates native contact or map minor was invalid'
matrices=[sp.zeros(len(bl)-1) for bl in M['blocks']]
for col,(bi,i,j) in enumerate(M['columns']):
 matrices[bi][i,j]=matrices[bi][j,i]=coef[col]
obj={'source':a.source,'gram_blocks':[[[str(x) for x in G.row(i)] for i in range(G.rows)] for G in matrices],
     'warning':'AFFINE IDENTITY ONLY. INDEFINITE IN GENERAL. DO NOT CLAIM PSD.'}
with open(a.output,'w') as f:json.dump(obj,f)
print('PASS exact complete-parent affine coefficient identity at requested native source')
print('NO PSD CLAIM. Output:',a.output)

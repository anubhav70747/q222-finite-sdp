#!/usr/bin/env python3
"""Materialize, query, or stream the ACTUAL global affine/PSD matrices.

Reads K364_FULL128_FACTORED_SPARSE_PENCIL.json generated by the companion
script. All coefficients exact Fractions. Data are not implicit operators:
- 66430 explicit upper entries (row,col,key) define each K moment LMI;
- every SG12 and SG13 parameter-base matrix is serialized;
- each 128 symmetry copy has exact source targets and variable/block offsets.

The default generates 3456 fully expanded rational affine equality rows.
Option --stream-all-lmi writes 8.5m+ explicit PSD upper entries to gzip JSONL
without loading them all in memory. This is optional since the same matrices
are already fully specified by indexed fixed bases plus copy tables.
"""
from __future__ import annotations
import argparse,gzip,json
from fractions import Fraction as F
from pathlib import Path
HERE=Path(__file__).resolve().parent

def load(path):
    with open(path,encoding='utf-8') as f:return json.load(f)
def tr_coeff(upper_entries):
    # Tr(MY) for a symmetric Y represented by upper triangle independent vars.
    d={}
    for i,j,x in upper_entries:
        k=i*(i+1)//2+j if False else None # ordinal computed below
        # upper n varies; use position index from n, supplied in caller
        d[(i,j)]=d.get((i,j),F(0))+F(x)*(1 if i==j else 2)
    return d

def upper_index(i,j,n):
    assert 0<=i<=j<n
    return i*n-i*(i-1)//2+(j-i)

def sparse_vector(entries):
    d={}
    for idx,x in entries:
        v=F(x)
        d[idx]=d.get(idx,F(0))+v
    return {k:v for k,v in d.items() if v}

def equality(lhs,constant,coefs,group_id,kind,local_number):
    c=sparse_vector(coefs)
    return {'id':27*group_id+local_number,'group_id':group_id,'kind':kind,
            'constant':str(F(constant)),
            'entries':[[i,str(c[i])] for i in sorted(c)]}

def materialize_equalities(data):
    T=data['T_source_columns'];faces=data['face_templates'];res=[]
    for g,offs in enumerate(data['group_copy_offsets']):
        bg=data['group_targets'][g]
        idx=offs['variables'];local=0
        for a in range(9):
            row=bg['K9x9'][a]
            terms=[(i-1,F(row[i])) for i in range(1,9) if F(row[i])]
            terms +=[(idx['K_dual_coeffs_y'][0]+k,-F(v)) for k,v in T[a]]
            terms +=[(idx['K_orthant_r'][0]+a,-1)]
            res.append(equality('K',F(row[0]),terms,g,'K_adjoint',local));local+=1
        for a in range(7):
            row=bg['SG12_7x9'][a]
            terms=[(i-1,F(row[i])) for i in range(1,9) if F(row[i])]
            terms +=[(idx['SG12_dual_upper_Y'][0]+upper_index(i,j,6),
                      -F(v)*(1 if i==j else 2)) for i,j,v in faces['SG12']['source_matrix_bases_6'][a]]
            terms +=[(idx['SG12_r'][0]+a,-1)]
            res.append(equality('F12',row[0],terms,g,'SG12_target',local));local+=1
        for a in range(3):
            terms=[(idx['SG12_dual_upper_Y'][0]+upper_index(i,j,6),
                    F(v)*(1 if i==j else 2)) for i,j,v in faces['SG12']['free_skew_matrix_bases_6'][a]]
            res.append(equality('skew',0,terms,g,'SG12_skew',local));local+=1
        for a in range(7):
            row=bg['SG13_7x9'][a]
            terms=[(i-1,F(row[i])) for i in range(1,9) if F(row[i])]
            for nm,k,loc in [('SG13_dual_upper_Y1',0,0),('SG13_dual_upper_Y2',1,1)]:
                terms +=[(idx[nm][0]+upper_index(i,j,3),-F(v)*(1 if i==j else 2))
                         for i,j,v in faces['SG13']['source_matrix_bases_3_and_3'][a][k]]
            terms +=[(idx['SG13_r'][0]+a,-1)]
            res.append(equality('F13',row[0],terms,g,'SG13_target',local));local+=1
        terms=[]
        for nm,k in [('SG13_dual_upper_Y1',0),('SG13_dual_upper_Y2',1)]:
            terms +=[(idx[nm][0]+upper_index(i,j,3),F(v)*(1 if i==j else 2))
                     for i,j,v in faces['SG13']['free_xi_matrix_bases_3_and_3'][k]]
        res.append(equality('xi',0,terms,g,'SG13_xi',local));local+=1
        assert local==27
    assert len(res)==3456 and all(row['id']==i for i,row in enumerate(res))
    return res

def lmi_upper_entries_for_group(data,g):
    """Yield (global_row,global_col,global_var_index,coeff) for PSD entries.
    Constants and q coefficients occur only in the 16 event diagonal block.
    Other blocks are exactly symmetric matrices of independent variables.
    """
    off=data['group_copy_offsets'][g];idx=off['variables'];blk=off['PSD_blocks']
    bp=blk['K_moment'][0];yp=idx['K_dual_coeffs_y'][0]
    for i,j,k in data['Gram_dual_moment_upper_entries_map_A_star']:
        yield bp+i,bp+j,yp+k,1
    for block, var,n in [('K_source_orthant','K_orthant_r',9),('SG12_orthant','SG12_r',7),('SG13_orthant','SG13_r',7)]:
        pos=blk[block][0];vp=idx[var][0]
        for k in range(n):yield pos+k,pos+k,vp+k,1
    for block,var,n in [('SG12_dual_PSD','SG12_dual_upper_Y',6),
                        ('SG13_dual_PSD_1','SG13_dual_upper_Y1',3),
                        ('SG13_dual_PSD_2','SG13_dual_upper_Y2',3)]:
        pos=blk[block][0];vp=idx[var][0]
        for i in range(n):
            for j in range(i,n):yield pos+i,pos+j,vp+upper_index(i,j,n),1

def event_global_entries(data):
    # LMI dimension 51088; event block starts at 51072.
    base=128*399
    for i,row in enumerate(data['physical_event_inequalities']):
        entries=[[j-1,v] for j,v in enumerate(row['nonnegative_4p']) if j>0 and v]
        yield {'global_row':base+i,'global_col':base+i,
               'constant':row['nonnegative_4p'][0],'q_variable_terms':entries}

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('--data',default=str(HERE/'K364_FULL128_FACTORED_SPARSE_PENCIL.json'))
    ap.add_argument('--out',default=str(HERE))
    ap.add_argument('--stream-all-lmi',action='store_true')
    ap.add_argument('--check-structural',action='store_true')
    args=ap.parse_args();data=load(args.data);p=Path(args.out);p.mkdir(parents=True,exist_ok=True)
    eqs=materialize_equalities(data)
    out=p/'K364_GLOBAL_ALL_3456_AFFINE_EQUALITIES.json'
    with open(out,'w') as f:json.dump({'variable_count':423176,'q_first_8':True,'rows':eqs},f,separators=(',',':'))
    with gzip.open(p/'K364_GLOBAL_ALL_3456_AFFINE_EQUALITIES.json.gz','wt') as f:json.dump({'variable_count':423176,'q_first_8':True,'rows':eqs},f,separators=(',',':'))
    with open(p/'K364_ALL_EVENT_LMI_ENTRIES.json','w') as f:json.dump(list(event_global_entries(data)),f,separators=(',',':'))
    if args.check_structural:
        assert len(eqs)==3456
        assert len(list(event_global_entries(data)))==16
        for g in (0,24,127):
            entries=lmi_upper_entries_for_group(data,g)
            actual=sum(1 for _ in entries)
            assert actual==66430+9+7+7+21+6+6, actual
    if args.stream_all_lmi:
        stream=p/'K364_GLOBAL_ALL_PSD_ENTRIES.jsonl.gz'
        count=0
        with gzip.open(stream,'wt') as f:
            for g in range(128):
                for i,j,idx,v in lmi_upper_entries_for_group(data,g):
                    f.write(json.dumps([i,j,idx,v],separators=(',',':'))+'\n');count+=1
            for t in event_global_entries(data):f.write(json.dumps(t,separators=(',',':'))+'\n');count+=1
        assert count==128*(66430+9+7+7+21+6+6)+16
        print('STREAMED',count,'exact LMI upper entries',stream)
    print('WROTE',out,'3456 equality rows, 16 event entries')

if __name__=='__main__':main()

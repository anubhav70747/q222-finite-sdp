"""Exact order-three source-curve cone and its dual; no solver or sweep."""
from pathlib import Path
import json
import sympy as s
z=s.symbols('z');b=s.Rational(2,5)
Ac=1+z/2;h=s.Rational(1,2);g=(1+z)/2;jc=(1+z)/2
Delta=2*(1+z)*(1+2*z);N=2*(1+z)
native=s.Matrix([1,0,
 (s.Rational(3,2)*Ac*(1+z)-Delta/2)/Delta,
 (1+z)*Ac*(1+z)/(4*g*Delta),Ac*N/Delta,
 3*Ac*(1+z)/(2*Delta),
 3*(1+z)*(1-z/2)*(1+z)/(4*jc*Delta),
 3*z*z*N/(4*(1-z/2)*Delta),0])
expected=s.Matrix([1,0,(2-5*z)/(8*(1+2*z)),(2+z)/(8*(1+2*z)),
 (2+z)/(2*(1+2*z)),3*(2+z)/(8*(1+2*z)),
 3*(2-z)/(8*(1+2*z)),3*z*z/(2*(2-z)*(1+2*z)),0])
assert (native-expected).applyfunc(s.cancel)==s.zeros(9,1)
scale=8*(2-z)*(1+2*z)
curve=s.Matrix([16+24*z-16*z*z,0,4-12*z+5*z*z,4-z*z,
 16-4*z*z,12-3*z*z,12-12*z+3*z*z,12*z*z,0])
assert (scale*native-curve).applyfunc(s.cancel)==s.zeros(9,1)

# Complete parent and contact jets: source z remains independent during
# differentiation, and is substituted by r^2 only after the testing jet.
u,v,W,X,Y,Z,r=s.symbols('u v W X Y Z r')
d,la,nn,mm,C,A,D,al,be=expected
Du=1+u*u;Dv=1+v*v
F=(4*la*Du*(W+v*X)**2+4*nn*Du*Dv*X*X+4*mm*(v*W-X+u*v*Y-u*Z)**2
 +4*C*Dv*(u*W-Y)**2+4*A*Du*Dv*Y*Y+(4*D+2*d)*(u*W+u*v*X-Y-v*Z)**2
 +(4*al+2*d)*Du*(v*Y-Z)**2+(4*be+2*d)*Dv*(X+u*Z)**2-2*d*Du*Dv*Z*Z)
contact={u:r,v:r,W:1,X:-r/2,Y:r/2,Z:1}
assert s.cancel(F.subs(contact).subs(z,r*r))==0
assert all(s.cancel(s.diff(F,var).subs(contact).subs(z,r*r))==0 for var in [u,v,W,X,Y,Z])

T=s.Matrix([[s.expand(q).coeff(z,k) for k in range(3)] for q in curve])
assert T.rank()==3
h0,h1,h2=s.symbols('h0 h1 h2');mom=s.Matrix([h0,h1,h2]);cc=T*mom
assert s.expand(cc[7]/12-h2)==0
assert s.expand(cc[3]/4+cc[7]/48-h0)==0
assert s.expand((cc[0]-4*cc[3]+cc[7])/24-h1)==0
w=h1*h1/h2;t=h2/h1;w0=h0-w
assert s.simplify(w0+w-h0)==0
assert s.simplify(w*t-h1)==0 and s.simplify(w*t*t-h2)==0

a0,a1,a2,tau=s.symbols('a0 a1 a2 tau')
G=s.Matrix([[a0,(a1-b*tau)/2],[(a1-b*tau)/2,a2+tau]])
assert s.expand((s.Matrix([1,z]).T*G*s.Matrix([1,z]))[0]+tau*z*(b-z)-a0-a1*z-a2*z*z)==0
tauB=(2*a0+b*a1)/(b*b);pb=a0+a1*b+a2*b*b
v0=s.Matrix([1,-1/b]);v1=s.Matrix([0,1/b])
assert (G.subs(tau,tauB)-a0*v0*v0.T-pb*v1*v1.T).applyfunc(s.expand)==s.zeros(2)
strict=s.Matrix([[1,b/2],[b/2,b*b/3]])
assert strict.det()==s.Rational(1,75)
assert b*b/2-b*b/3==s.Rational(2,75)
receipt={'source_order':['d','lambda','n','m','C','A','D','alpha','beta'],
 'native_specialization_exact':True,'scaled_polynomial_curve_exact':True,
 'complete_parent_contact_and_six_testing_state_derivatives_exact':True,
 'source_and_testing_z_independent_during_differentiation':True,
 'T':[[str(x) for x in row] for row in T.tolist()],'T_rank':3,
 'endpoint_b':str(b),'inverse_moment_map_exact':True,
 'two_atom_moment_reconstruction_exact':True,'dual_polynomial_identity_exact':True,
 'constructive_dual_tauB_identity_exact':True,
 'strict_moment_point':['1',str(b/2),str(b*b/3)],
 'strict_moment_matrix_determinant':'1/75','strict_localizer':'2/75',
 'PSD_order_source_cone':3,'PSD_order_dual_cone':3,
 'scope':'Exact cone generated by this continuous valid C2 source family and its dual. Physical global validity uses the native contact theorem plus closed endpoint limits; not full Q222.',
 'no_NPA_exclusion_replay':True,'no_solver_or_numerical_sweep':True}

U=sym(u); V=sym(v); aa=s.Matrix([1,a,a*a])
positive=s.expand(((a-left)*(aa.T*U*aa)[0]+(right-a)*(aa.T*V*aa)[0]))
pair=sum(positive.coeff(a,i)*y[i] for i in range(6))
assert s.expand(pair-s.trace(U*ML)-s.trace(V*MR))==0

curve=T*mon/scale
assert all(s.cancel(clear*c-v)==0 for c,v in zip(source,curve))
assert s.factor(B-(32*a**3-208*a*a-29*a+1)/1024)==0
left=s.Rational(3,4); right=s.Integer(2)
power=s.Poly(s.expand(B.subs(a,left+(right-left)*z)),z)
bern=[s.factor(sum(power.coeff_monomial(z**i)*s.binomial(j,i)/s.binomial(3,i)
                   for i in range(j+1))) for j in range(4)]
assert bern==[-s.Rational(497,4096),-s.Rational(1463,6144),
              -s.Rational(1737,4096),-s.Rational(633,1024)]
